export const translations: Record<Locale, TranslationDictionary> = { en, es, pt, fr }

export function isLocale(value: string | null | undefined): value is Locale {
  return locales.includes(value as Locale)
}

export function detectLocale(languages: readonly string[] = []): Locale {
  for (const language of languages) {
    const candidate = language.toLowerCase().split('-')[0]
    if (isLocale(candidate)) return candidate
  }
  return 'en'
}

export function translate(locale: Locale, key: TranslationKey, variables: Record<string, string | number> = {}) {
  return Object.entries(variables).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    translations[locale][key],
  )
}
